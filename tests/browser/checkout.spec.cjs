const { test, expect } = require('@playwright/test')
const { randomUUID } = require('node:crypto')
const { productId, smallId, mediumId, customer, items } = require('../database.cjs')
const item = { product_id: productId, variant_id: smallId, name: 'Test Lawn Suit', slug: 'test-lawn-suit', size: 'S', price: 2700, sale_price: null, quantity: 1, stock: 5, image_url: '' }
const state = async (request) => (await request.get('http://127.0.0.1:3111/__state')).json()
test.beforeEach(async ({ request }) => { await request.post('http://127.0.0.1:3111/__reset') })
async function fillCustomer(page) {
  await page.getByLabel('Full Name *', { exact: true }).fill(customer.full_name)
  await page.getByLabel('Email *', { exact: true }).fill(customer.email)
  await page.getByLabel('Phone Number *', { exact: true }).fill(customer.phone)
  await page.getByLabel('Full Address *', { exact: true }).fill(customer.address)
  await page.getByLabel('City *', { exact: true }).fill(customer.city)
}
async function seedCart(page) {
  await page.addInitScript((item) => {
    if (!sessionStorage.getItem('test-seeded')) {
      localStorage.setItem('aabroze_cart', JSON.stringify([item]))
      sessionStorage.setItem('test-seeded', '1')
    }
  }, item)
}

