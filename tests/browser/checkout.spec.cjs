test('lost response after commit → refresh → retry returns the same order', async ({ page, request }) => {
  await seedCart(page)
  await page.goto('/checkout')
  await fillCustomer(page)
  await page.route('**/api/orders', async (route) => { await route.fetch(); await route.abort() }, { times: 1 })
  await page.getByRole('button', { name: 'Place Order', exact: true }).click()
  await expect(page.locator('main').getByRole('alert')).toContainText('Retry this checkout')
  const before = await state(request)
  expect(before.orders).toHaveLength(1)
  await page.reload()
  await page.getByRole('button', { name: 'Retry / Confirm Order' }).click()
  await expect(page.getByRole('heading', { name: 'Your order has been placed successfully.' })).toBeVisible()
  const after = await state(request)
  expect(after.orders).toHaveLength(1)
  expect(after.orders[0].order_number).toBe(before.orders[0].order_number)
})

test('API rejects unavailable size and invalid customer, ignores supplied price, protects email retries', async ({ request }) => {
  const bad = await request.post('/api/orders', { data: { customer: { ...customer, email: 'bad' }, items } })
  expect(bad.status()).toBe(400)
  const unavailable = await request.post('/api/orders', { data: { customer, items: [{ ...items[0], quantity: 10 }] } })
  expect(unavailable.status()).toBe(400)
  const placed = await request.post('/api/orders', { data: { customer, items: [{ ...items[0], price: 1 }] } })
  expect(placed.status()).toBe(200)
  expect((await placed.json()).data.total).toBe(5600)
  const competing = await Promise.all([1, 2].map(() => request.post('/api/orders', {
    data: { customer: { ...customer, idempotency_key: randomUUID() }, items: [{ ...items[0], quantity: 2 }] },
  })))
  expect(competing.map((response) => response.status()).sort()).toEqual([200, 400])
  expect((await state(request)).orders).toHaveLength(2)
  expect((await request.post('/api/orders/retry-emails')).status()).toBe(401)
})
